#!/usr/bin/env python3
"""Check the human-facing files of the repository.

Usage (from the repository root, or with --root):

    python3 .kiro/specs/english-docs/check_docs.py check [--root PATH] [--files PATH...]
    python3 .kiro/specs/english-docs/check_docs.py extract OUTDIR [--root PATH]

Mode `check` reports one finding per line as `<path>:<line>: <kind>: <detail>`
and ends with a summary. Kinds:

    japanese        a line of a human-facing file that contains Japanese characters
    kiro            a line of a human-facing file that contains ".kiro" (any case)
    spec-term       a line of a human-facing document that mentions specs,
                    spec names, steering or Kiro
    missing-file    a relative link of a human-facing document whose target
                    does not exist in the working tree
    missing-anchor  a link with a fragment whose anchor is not generated by any
                    heading of the target Markdown file
    pending         a missing-file whose target is a release-automation document;
                    not counted as a failure

The exit status is 1 when there is at least one finding other than `pending`,
and 0 otherwise. It is 2 when a `--files` path is not in the checked set
(an untracked or nonexistent file).

Mode `extract` writes every ```c code block of the human-facing documents that
defines `main` or `wmain` to `OUTDIR/<doc>-<n>.c`, where `<doc>` is the path of
the document with `/` replaced by `_` and `<n>` is the number of the C block
within that document (counting every C block, from 1). It writes one line per
block to `OUTDIR/manifest.txt` as `<file> <entry> <source>:<line>`, where
`<entry>` is `main` or `wmain` and `<line>` is the line of the opening fence.
Existing files are overwritten; the exit status is 0.

The script uses only the Python standard library and never modifies the
repository (apart from what `extract` writes to OUTDIR).
"""

import argparse
import os
import re
import subprocess
import sys
import urllib.parse

# ---------------------------------------------------------------------------
# File sets (the single place that decides what is checked)
# ---------------------------------------------------------------------------

# Tracked paths excluded from every check: the AI working areas.
EXCLUDED_PREFIXES = (".kiro/", ".claude/")
EXCLUDED_FILES = ("CLAUDE.md",)

# Release-automation documents. Links to them that do not resolve are
# reported as `pending` instead of `missing-file`.
PENDING_TARGETS = ("CHANGELOG.md", "docs/releasing.md", "docs/versioning.md")

# Paths created or changed by release-automation (requirement 10.4). Findings
# in them are counted separately in the summary and are not fixed by
# english-docs.
RELEASE_AUTOMATION_FILES = PENDING_TARGETS + (
    "include/clargs/version.h", "CMakeLists.txt", "tests/CMakeLists.txt",
    "tests/public/version_test.c",
)
RELEASE_AUTOMATION_PREFIXES = (
    "tools/", "tests/release/", ".github/workflows/", "cmake/", "tests/consumer/",
)


def is_target_file(path):
    """Return True if the tracked path is a human-facing file."""
    if path.startswith(EXCLUDED_PREFIXES) or path in EXCLUDED_FILES:
        return False
    return True


def is_human_doc(path):
    """Return True if the human-facing file is a human-facing document."""
    if path in ("README.md", "CONTRIBUTING.md"):
        return True
    return path.startswith("docs/") and path.endswith(".md")


def is_release_automation(path):
    return path in RELEASE_AUTOMATION_FILES or path.startswith(RELEASE_AUTOMATION_PREFIXES)


def tracked_files(root):
    out = subprocess.run(
        ["git", "-C", root, "ls-files", "-z"],
        check=True, stdout=subprocess.PIPE,
    ).stdout.decode("utf-8")
    return sorted(p for p in out.split("\0") if p)


# ---------------------------------------------------------------------------
# Line checks
# ---------------------------------------------------------------------------

# CJK symbols and punctuation, hiragana, katakana, CJK extension A, CJK unified
# ideographs, CJK compatibility ideographs, halfwidth and fullwidth forms.
# Other non-ASCII characters (box drawing and so on) are not Japanese.
JAPANESE_RE = re.compile(
    "[　-〿぀-ヿ㐀-䶿一-鿿豈-﫿＀-￯]"
)
KIRO_RE = re.compile(r"\.kiro", re.IGNORECASE)
SPEC_NAMES = (
    "build-foundation", "core-runtime", "command-schema", "argv-parser",
    "help-formatter", "english-docs", "release-automation",
)
# `\bspecs?\b` matches whole words only, so "specification" and "specific"
# are not reported.
SPEC_TERM_RE = re.compile(
    r"\bspecs?\b|steering|kiro|" + "|".join(re.escape(n) for n in SPEC_NAMES),
    re.IGNORECASE,
)


def excerpt(line, limit=80):
    text = line.strip()
    return text if len(text) <= limit else text[: limit - 3] + "..."


# ---------------------------------------------------------------------------
# Markdown: code fences, headings, anchors, links
# ---------------------------------------------------------------------------

FENCE_RE = re.compile(r"^\s*(`{3,}|~{3,})")
HEADING_RE = re.compile(r"^ {0,3}(#{1,6})\s+(.*?)\s*#*\s*$")
INLINE_LINK_RE = re.compile(r"\]\(\s*<?([^)\s>]*)>?(?:\s+\"[^\"]*\")?\s*\)")
REF_DEF_RE = re.compile(r"^\s{0,3}\[[^\]]+\]:\s*<?(\S+?)>?(?:\s+.*)?$")
CODE_SPAN_RE = re.compile(r"(`+)(.+?)\1")
MD_LINK_TEXT_RE = re.compile(r"!?\[([^\]]*)\]\([^)]*\)")
HTML_TAG_RE = re.compile(r"<[^>]+>")
SCHEME_RE = re.compile(r"^[A-Za-z][A-Za-z0-9+.-]*:")


def outside_fences(lines):
    """Yield (line number, line) for the lines that are not in a code block."""
    fence = None
    for number, line in enumerate(lines, 1):
        m = FENCE_RE.match(line)
        if fence is None:
            if m:
                fence = m.group(1)
                continue
            yield number, line
        elif m and m.group(1)[0] == fence[0] and len(m.group(1)) >= len(fence) \
                and line.strip() == m.group(1):
            fence = None


def github_anchor(heading_text):
    """Convert heading text to the anchor GitHub generates (before dedup)."""
    # Code spans render as their literal content, so unwrap them first and
    # keep their text out of the HTML tag removal.
    parts = re.split(r"(`+)(.+?)\1", heading_text)
    pieces = []
    for i in range(0, len(parts), 3):
        text = MD_LINK_TEXT_RE.sub(r"\1", parts[i])
        pieces.append(HTML_TAG_RE.sub("", text))
        if i + 2 < len(parts):
            pieces.append(parts[i + 2])
    text = "".join(pieces)
    text = text.strip().lower()
    text = re.sub(r"[^\w\- ]", "", text)
    return text.replace(" ", "-")


def anchors_of(lines):
    """Return the set of anchors made from the headings outside code blocks."""
    seen = {}
    anchors = set()
    for _, line in outside_fences(lines):
        m = HEADING_RE.match(line)
        if not m:
            continue
        base = github_anchor(m.group(2))
        count = seen.get(base, 0)
        anchors.add(base if count == 0 else "%s-%d" % (base, count))
        seen[base] = count + 1
    return anchors


def links_of(lines):
    """Yield (line number, target) for every link outside code blocks and spans."""
    for number, line in outside_fences(lines):
        text = CODE_SPAN_RE.sub("", line)
        for m in INLINE_LINK_RE.finditer(text):
            yield number, m.group(1)
        m = REF_DEF_RE.match(text)
        if m:
            yield number, m.group(1)


OPEN_FENCE_RE = re.compile(r"^(\s*)(`{3,}|~{3,})\s*([^`\s]*)")
# A line that defines `main` or `wmain`: optional specifiers and the return
# type before the name (or the name alone at the start of a line, when the
# type is on the line before), then the parameters and, on the same line,
# nothing but the opening brace and the body. A declaration (`;` after the
# parameters), a call or a mention in a comment does not count.
ENTRY_RE = re.compile(
    r"^\s*(?:[A-Za-z_]\w*[\s*]+)*(w?main)\s*\([^;)]*(?:\)\s*(?:\{.*)?)?$")


def code_blocks(lines):
    """Yield (line of the opening fence, info word, lines) for every fenced block.

    The indentation of the opening fence is removed from the lines of the
    block, as CommonMark does for a block in a list item.
    """
    block = None
    for number, line in enumerate(lines, 1):
        if block is None:
            m = OPEN_FENCE_RE.match(line)
            if m:
                block = (number, m.group(3).lower(), len(m.group(1)), m.group(2), [])
            continue
        start, info, indent, fence, body = block
        m = FENCE_RE.match(line)
        if m and m.group(1)[0] == fence[0] and len(m.group(1)) >= len(fence) \
                and line.strip() == m.group(1):
            yield start, info, body
            block = None
            continue
        strip = len(line) - len(line.lstrip(" "))
        body.append(line[min(indent, strip):])


def entry_of(body):
    """Return "main" or "wmain" if the block defines it, else None."""
    for line in body:
        m = ENTRY_RE.match(line)
        if m:
            return m.group(1)
    return None


# ---------------------------------------------------------------------------
# Checker
# ---------------------------------------------------------------------------

class Checker:
    def __init__(self, root):
        self.root = os.path.abspath(root)
        self.tracked = tracked_files(self.root)
        self.targets = [p for p in self.tracked if is_target_file(p)]
        self.docs = [p for p in self.targets if is_human_doc(p)]
        self.findings = []
        self.skipped = []
        self._lines = {}
        self._anchors = {}

    def read_lines(self, path):
        """Return the lines of a repository file, or None if it is not UTF-8 text."""
        if path not in self._lines:
            try:
                with open(os.path.join(self.root, path), "r", encoding="utf-8") as f:
                    self._lines[path] = f.read().splitlines()
            except (UnicodeDecodeError, OSError):
                self._lines[path] = None
        return self._lines[path]

    def anchors(self, path):
        if path not in self._anchors:
            lines = self.read_lines(path)
            self._anchors[path] = anchors_of(lines) if lines is not None else set()
        return self._anchors[path]

    def add(self, path, line, kind, detail):
        self.findings.append((path, line, kind, detail))

    def check_lines(self, path, lines):
        doc = is_human_doc(path)
        for number, line in enumerate(lines, 1):
            m = JAPANESE_RE.search(line)
            if m:
                self.add(path, number, "japanese", excerpt(line))
            if KIRO_RE.search(line):
                self.add(path, number, "kiro", excerpt(line))
            if doc:
                terms = sorted({t.group(0).lower() for t in SPEC_TERM_RE.finditer(line)})
                if terms:
                    self.add(path, number, "spec-term", ", ".join(terms))

    def check_links(self, path, lines):
        base_dir = os.path.dirname(path)
        for number, target in links_of(lines):
            if not target or SCHEME_RE.match(target):
                continue
            file_part, _, fragment = target.partition("#")
            file_part = urllib.parse.unquote(file_part)
            fragment = urllib.parse.unquote(fragment)
            if file_part:
                if file_part.startswith("/"):
                    resolved = file_part.lstrip("/")
                else:
                    resolved = os.path.join(base_dir, file_part)
                resolved = os.path.normpath(resolved).replace(os.sep, "/")
            else:
                resolved = path
            full = os.path.join(self.root, resolved)
            if resolved.startswith("../") or not os.path.exists(full):
                kind = "pending" if resolved in PENDING_TARGETS else "missing-file"
                self.add(path, number, kind, target)
                continue
            if fragment and resolved.endswith(".md") and os.path.isfile(full):
                # GitHub anchors are lowercase; a fragment in another case
                # does not match.
                if fragment not in self.anchors(resolved):
                    self.add(path, number, "missing-anchor", target)

    def run(self, only=None):
        for path in self.targets:
            if only is not None and path not in only:
                continue
            lines = self.read_lines(path)
            if lines is None:
                self.skipped.append(path)
                continue
            self.check_lines(path, lines)
            if is_human_doc(path):
                self.check_links(path, lines)
        self.findings.sort(key=lambda f: (f[0], f[1], KINDS.index(f[2])))


KINDS = ("japanese", "kiro", "spec-term", "missing-file", "missing-anchor", "pending")


def print_summary(checker, out):
    groups = (
        ("english-docs", lambda p: not is_release_automation(p)),
        ("release-automation", is_release_automation),
    )
    out.write("\nSummary\n")
    for name, belongs in groups:
        selected = [f for f in checker.findings if belongs(f[0])]
        counts = {k: 0 for k in KINDS}
        for f in selected:
            counts[f[2]] += 1
        detail = ", ".join("%s %d" % (k, counts[k]) for k in KINDS)
        out.write("  %s total: %d (%s)\n" % (name, len(selected), detail))
        if name == "release-automation" and selected:
            out.write("    (findings in release-automation files are reported to "
                      "release-automation, not fixed here)\n")
        per_file = {}
        for f in selected:
            per_file.setdefault(f[0], {}).setdefault(f[2], 0)
            per_file[f[0]][f[2]] += 1
        for path in sorted(per_file):
            detail = ", ".join("%s %d" % (k, per_file[path][k])
                               for k in KINDS if k in per_file[path])
            out.write("    %s: %s\n" % (path, detail))
    for path in checker.skipped:
        out.write("  skipped (not UTF-8 text): %s\n" % path)
    failures = sum(1 for f in checker.findings if f[2] != "pending")
    pending = len(checker.findings) - failures
    out.write("  failures: %d, pending: %d\n" % (failures, pending))
    return failures


def cmd_check(args):
    checker = Checker(args.root)
    only = None
    if args.files is not None:
        only = set()
        for p in args.files:
            absolute = os.path.abspath(p) if os.path.isabs(p) else os.path.join(checker.root, p)
            only.add(os.path.relpath(absolute, checker.root).replace(os.sep, "/"))
        unknown = sorted(only - set(checker.targets))
        if unknown:
            # The target set is fixed to `git ls-files`; a path outside it
            # would otherwise pass silently with no findings.
            for p in unknown:
                reason = "exists but is not tracked" if os.path.exists(
                    os.path.join(checker.root, p)) else "does not exist"
                sys.stderr.write(
                    "check_docs.py: --files %s: not in the checked set (%s, or it "
                    "is excluded). For a new file, run `git add -N %s` so that "
                    "it appears in `git ls-files`.\n" % (p, reason, p))
            return 2
    checker.run(only)
    out = sys.stdout
    for path, line, kind, detail in checker.findings:
        out.write("%s:%d: %s: %s\n" % (path, line, kind, detail))
    failures = print_summary(checker, out)
    return 1 if failures else 0


def cmd_extract(args):
    checker = Checker(args.root)
    outdir = args.outdir
    os.makedirs(outdir, exist_ok=True)
    manifest = []
    for path in checker.docs:
        lines = checker.read_lines(path)
        if lines is None:
            continue
        n = 0
        for start, info, body in code_blocks(lines):
            if info != "c":
                continue
            n += 1
            entry = entry_of(body)
            if entry is None:
                continue
            name = "%s-%d.c" % (path.replace("/", "_"), n)
            with open(os.path.join(outdir, name), "w", encoding="utf-8", newline="\n") as f:
                f.write("\n".join(body) + "\n")
            manifest.append("%s %s %s:%d" % (name, entry, path, start))
    with open(os.path.join(outdir, "manifest.txt"), "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(line + "\n" for line in manifest))
    for line in manifest:
        sys.stdout.write(line + "\n")
    sys.stdout.write("extracted %d example(s) to %s\n" % (len(manifest), outdir))
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description="Check the human-facing files.")
    sub = parser.add_subparsers(dest="mode", required=True)
    check = sub.add_parser("check", help="report language, link and anchor problems")
    check.add_argument("--root", default=".", help="repository root (default: .)")
    check.add_argument("--files", nargs="+", metavar="PATH",
                       help="limit the report to these files (relative to the root); "
                            "a path outside the checked set exits with status 2")
    extract = sub.add_parser("extract", help="write the C examples that define main or wmain")
    extract.add_argument("outdir", help="directory to write the examples and manifest.txt to")
    extract.add_argument("--root", default=".", help="repository root (default: .)")
    args = parser.parse_args(argv)
    if args.mode == "check":
        return cmd_check(args)
    if args.mode == "extract":
        return cmd_extract(args)
    return 2


if __name__ == "__main__":
    sys.exit(main())
